/**
 * Calcule les métadonnées du transcript
 */
function calculateTranscriptMetadata(
  transcript: TranscriptSegment[],
  videoInfo: YouTubeVideoInfo
): YouTubeTranscriptResult['metadata'] {
  const totalDuration = transcript.reduce((sum, seg) => sum + seg.duration, 0);
  const allText = transcript.map(seg => seg.text).join(' ');
  const wordCount = allText.split(/\s+/).filter(w => w.length > 0).length;
  
  return {
    totalDuration,
    wordCount,
    language: videoInfo.language,
    isAutoGenerated: true,
    availableLanguages: [videoInfo.language, 'en'],
    lastUpdated: new Date().toISOString()
  };
}

/**
 * Formate le transcript pour l'affichage
 */
export function formatTranscriptForDisplay(
  result: YouTubeTranscriptResult,
  options: {
    includeTimestamps?: boolean;
    includeVideoInfo?: boolean;
    format?: 'text' | 'srt' | 'json';
    groupByParagraph?: boolean;
  } = {}
): string {
  const {
    includeTimestamps = true,
    includeVideoInfo = true,
    format = 'text',
    groupByParagraph = false
  } = options;

  let formattedText = '';

  // Informations de la vidéo
  if (includeVideoInfo) {
    formattedText += `# ${result.videoInfo.title}\n\n`;
    formattedText += `📺 **Chaîne :** ${result.videoInfo.channelTitle}\n`;
    formattedText += `📅 **Publié :** ${new Date(result.videoInfo.publishedAt).toLocaleDateString()}\n`;
    formattedText += `👁️ **Vues :** ${result.videoInfo.viewCount.toLocaleString()}\n`;
    formattedText += `⏱️ **Durée :** ${formatDuration(result.metadata.totalDuration)}\n`;
    formattedText += `📝 **Mots :** ${result.metadata.wordCount}\n\n`;
  }

  // Formatage du transcript
  switch (format) {
    case 'srt':
      formattedText += formatSRT(result.transcript);
      break;
    case 'json':
      formattedText += JSON.stringify(result.transcript, null, 2);
      break;
    default:
      formattedText += formatTextTranscript(result.transcript, includeTimestamps, groupByParagraph);
  }

  return formattedText;
}

/**
 * Formate le transcript en texte simple
 */
function formatTextTranscript(
  transcript: TranscriptSegment[],
  includeTimestamps: boolean,
  groupByParagraph: boolean
): string {
  let text = '';
  
  if (groupByParagraph) {
    // Grouper par paragraphes logiques
    const paragraphs: string[] = [];
    let currentParagraph = '';
    
    transcript.forEach((segment, index) => {
      const segmentText = includeTimestamps 
        ? `[${formatTimestamp(segment.start)}] ${segment.text}`
        : segment.text;
      
      currentParagraph += segmentText + ' ';
      
      // Nouveau paragraphe toutes les 3-4 segments ou aux points
      if (index % 3 === 2 || segment.text.endsWith('.')) {
        paragraphs.push(currentParagraph.trim());
        currentParagraph = '';
      }
    });
    
    if (currentParagraph.trim()) {
      paragraphs.push(currentParagraph.trim());
    }
    
    text = paragraphs.join('\n\n');
  } else {
    // Format simple avec timestamps
    transcript.forEach(segment => {
      if (includeTimestamps) {
        text += `[${formatTimestamp(segment.start)}] ${segment.text}\n\n`;
      } else {
        text += `${segment.text}\n\n`;
      }
    });
  }
  
  return text.trim();
}

/**
 * Formate le transcript en SRT
 */
function formatSRT(transcript: TranscriptSegment[]): string {
  let srt = '';
  let index = 1;
  
  transcript.forEach(segment => {
    const startTime = formatSRTTimestamp(segment.start);
    const endTime = formatSRTTimestamp(segment.start + segment.duration);
    
    srt += `${index}\n`;
    srt += `${startTime} --> ${endTime}\n`;
    srt += `${segment.text}\n\n`;
    index++;
  });
  
  return srt.trim();
}

/**
 * Formate un timestamp en secondes
 */
function formatTimestamp(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  
  if (hours > 0) {
    return `${hours}:${minutes.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
  } else {
    return `${minutes}:${secs.toString().padStart(2, '0')}`;
  }
}

/**
 * Formate un timestamp SRT
 */
function formatSRTTimestamp(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  const ms = Math.floor((seconds % 1) * 1000);
  
  return `${hours.toString().padStart(2, '0')}:${minutes.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')},${ms.toString().padStart(3, '0')}`;
}

/**
 * Formate une durée ISO 8601
 */
function formatDuration(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  
  if (hours > 0) {
    return `${hours}h ${minutes}m ${secs}s`;
  } else if (minutes > 0) {
    return `${minutes}m ${secs}s`;
  } else {
    return `${secs}s`;
  }
}

/**
 * Parse le nombre de vues
 */
function parseViewCount(viewText: string): number {
  // Extraire le nombre depuis "1.2M vues", "345K vues", etc.
  const match = viewText.match(/([\d.]+)([KM]?)\s*vues?/i);
  if (!match) return 0;
  
  const number = parseFloat(match[1]);
  const unit = match[2]?.toUpperCase();
  
  switch (unit) {
    case 'K': return Math.floor(number * 1000);
    case 'M': return Math.floor(number * 1000000);
    default: return Math.floor(number);
  }
}

/**
 * Valide si une URL YouTube est supportée
 */
export function validateYouTubeURL(url: string): { isValid: boolean; videoId?: string; error?: string } {
  const videoId = extractVideoId(url);
  
  if (!videoId) {
    return {
      isValid: false,
      error: 'URL YouTube invalide. Formats supportés: youtube.com/watch?v=ID, youtu.be/ID'
    };
  }
  
  return { isValid: true, videoId };
}

/**
 * Recherche des transcripts disponibles pour une vidéo
 */
export async function getAvailableLanguages(videoId: string): Promise<string[]> {
  try {
    // Liste des langues communes à tester
    const languages = ['fr', 'en', 'es', 'de', 'it', 'pt', 'ru', 'ja', 'ko', 'zh'];
    const availableLanguages: string[] = [];
    
    for (const lang of languages) {
      const url = `https://video.google.com/timedtext?lang=${lang}&v=${videoId}`;
      
      try {
        const response = await fetch(url, { method: 'HEAD' });
        if (response.ok) {
          availableLanguages.push(lang);
        }
      } catch {
        // Ignorer les erreurs
      }
    }
    
    return availableLanguages;
  } catch (error) {
    console.warn('⚠️ Erreur vérification langues:', error);
    return ['fr', 'en']; // Langues par défaut
  }
}
