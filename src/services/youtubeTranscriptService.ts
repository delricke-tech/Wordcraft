/**
 * Parse le XML des transcripts YouTube
 */
function parseTranscriptXML(xmlText: string): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  
  try {
    // Parser basique du XML
    const textMatches = xmlText.matchAll(/<text start="([^"]+)" dur="([^"]+)">([^<]+)<\/text>/g);
    
    for (const match of textMatches) {
      const start = parseFloat(match[1]);
      const duration = parseFloat(match[2]);
      const text = match[3]
        .replace(/&quot;/g, '"')
        .replace(/&#39;/g, "'")
        .replace(/&amp;/g, '&')
        .trim();
      
      if (text && text.length > 0) {
        segments.push({
          start,
          duration,
          text,
          confidence: 0.9
        });
      }
    }
    
    return segments;
  } catch (error) {
    console.error('❌ Erreur parsing XML:', error);
    return [];
  }
}

