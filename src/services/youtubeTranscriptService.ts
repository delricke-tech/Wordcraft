// Types
export interface YouTubeVideoInfo {
  videoId: string;
  title: string;
  description: string;
  channelTitle: string;
  publishedAt: string;
  duration: string; // ISO 8601 duration
  thumbnailUrl: string;
  viewCount: number;
  likeCount: number;
  tags: string[];
  language: string;
  category: string;
}

export interface TranscriptSegment {
  start: number; // Secondes
  duration: number; // Secondes
  text: string;
  confidence?: number; // 0-1
  speaker?: string;
}

export interface YouTubeTranscriptResult {
  videoInfo: YouTubeVideoInfo;
  transcript: TranscriptSegment[];
  metadata: {
    totalDuration: number; // Secondes
    wordCount: number;
    language: string;
    isAutoGenerated: boolean;
    availableLanguages: string[];
    lastUpdated: string;
  };
  extraction: {
    method: 'youtube-api' | 'ytdlp' | 'fallback';
    timestamp: string;
    confidence: number; // 0-1
  };
}

export interface TranscriptOptions {
  language?: string; // Code langue (fr, en, etc.)
  includeTimestamps?: boolean;
  includeSpeakerLabels?: boolean;
  maxSegments?: number;
  format?: 'text' | 'json' | 'srt';
}

/**
 * Extrait le transcript d'une vidéo YouTube
 */
export async function extractYouTubeTranscript(
  videoUrl: string,
  options: TranscriptOptions = {}
): Promise<YouTubeTranscriptResult> {
  const startTime = Date.now();
  
  try {
    console.log('🎥 ===== EXTRACTION YOUTUBE TRANSCRIPT =====');
    console.log('  - URL:', videoUrl);
    console.log('  - Options:', options);

    // Extraire l'ID de la vidéo
    const videoId = extractVideoId(videoUrl);
    if (!videoId) {
      throw new Error('URL YouTube invalide');
    }

    console.log('  - Video ID:', videoId);

    // Obtenir les informations de la vidéo
    const videoInfo = await getYouTubeVideoInfo(videoId);

    // Tenter d'extraire le transcript
    let transcript = await extractTranscriptWithAPI(videoId, options);
    
    // Si l'API échoue, essayer le fallback
    if (!transcript || transcript.length === 0) {
      console.warn('⚠️ API YouTube échouée, tentative fallback...');
      transcript = await extractTranscriptWithFallback();
    }

    // Calculer les métadonnées
    const metadata = calculateTranscriptMetadata(transcript, videoInfo);
    
    const processingTime = Date.now() - startTime;
    console.log(`✅ Transcript extrait en ${processingTime}ms`);
    console.log(`  - Durée totale: ${metadata.totalDuration}s`);
    console.log(`  - Mots: ${metadata.wordCount}`);
    console.log(`  - Segments: ${transcript.length}`);

    return {
      videoInfo,
      transcript,
      metadata,
      extraction: {
        method: 'youtube-api',
        timestamp: new Date().toISOString(),
        confidence: 0.9
      }
    };

  } catch (error) {
    console.error('💥 Erreur extraction YouTube:', error);
    throw new Error(`Échec de l'extraction: ${error instanceof Error ? error.message : 'Erreur inconnue'}`);
  }
}

/**
 * Extrait l'ID d'une vidéo YouTube depuis l'URL
 */
function extractVideoId(url: string): string | null {
  const patterns = [
    /(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/embed\/)([^&\n?#]+)/,
    /youtube\.com\/watch\?.*v=([^&\n?#]+)/
  ];

  for (const pattern of patterns) {
    const match = url.match(pattern);
    if (match && match[1]) {
      return match[1];
    }
  }

  return null;
}

/**
 * Obtient les informations de la vidéo YouTube
 */
async function getYouTubeVideoInfo(videoId: string): Promise<YouTubeVideoInfo> {
  try {
    // Note: En production, il faudrait utiliser l'API YouTube Data v3 avec clé API
    // Pour l'instant, on utilise une méthode alternative avec oembed
    
    const oembedUrl = `https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${videoId}&format=json`;
    
    const response = await fetch(oembedUrl);
    if (!response.ok) {
      throw new Error(`HTTP error: ${response.status}`);
    }

    const data = await response.json();
    
    // Extraire des informations supplémentaires depuis la page
    const pageResponse = await fetch(`https://www.youtube.com/watch?v=${videoId}`);
    const pageText = await pageResponse.text();
    
    // Parser les métadonnées depuis la page (basique)
    const titleMatch = pageText.match(/<title>([^<]+)<\/title>/);
    const descriptionMatch = pageText.match(/"shortDescription":"([^"]+)"/);
    const durationMatch = pageText.match(/"lengthSeconds":"(\d+)"/);
    const viewCountMatch = pageText.match(/"views":{"simpleText":"([^"]+)"/);
    
    return {
      videoId,
      title: data.title || titleMatch?.[1] || 'Titre inconnu',
      description: descriptionMatch?.[1] || '',
      channelTitle: data.author_name || 'Chaîne inconnue',
      publishedAt: new Date().toISOString(), // À extraire de la page
      duration: durationMatch ? `PT${durationMatch[1]}S` : '',
      thumbnailUrl: data.thumbnail_url || '',
      viewCount: parseViewCount(viewCountMatch?.[1] || '0'),
      likeCount: 0, // Non disponible via oembed
      tags: [], // À extraire de la page
      language: 'auto',
      category: 'General'
    };

  } catch (error) {
    console.warn('⚠️ Erreur récupération infos vidéo:', error);
    
    // Retourner des infos basiques
    return {
      videoId,
      title: `Vidéo YouTube ${videoId}`,
      description: '',
      channelTitle: 'Chaîne inconnue',
      publishedAt: new Date().toISOString(),
      duration: '',
      thumbnailUrl: `https://img.youtube.com/vi/${videoId}/maxresdefault.jpg`,
      viewCount: 0,
      likeCount: 0,
      tags: [],
      language: 'auto',
      category: 'General'
    };
  }
}

